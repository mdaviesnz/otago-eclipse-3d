#!/usr/bin/env python3
"""
Generate the path of totality that the overview map draws.

Writes eclipse-path.js: the northern limit, the southern limit and the centre line, at sea
level, from the same library and ΔT as the catalogue and the browser. Run it again whenever
DELTA_T_SECONDS or the astronomy-engine version changes; tests/check_static.py fails if the
file was made with a different ΔT.

The path is followed from 146 E, over eastern Australia, to where it runs into sunset east of
New Zealand. It is a line on a map, so a point every quarter of a degree of longitude is
plenty: straight segments between them stray from the true curve by a few metres.

Usage
  python build_path.py
"""

from __future__ import annotations

import json
from pathlib import Path

import eclipse

LON_FROM = 146.0
LON_STEP = 0.25
LON_GIVE_UP = 190.0
OUT = Path(__file__).parent.parent / "eclipse-path.js"

HEADER = """\
// The path of totality on the overview map: [latitude, longitude] along the northern limit, the
// southern limit and the centre line, at sea level. East of New Zealand the path runs into
// sunset, and the limits there follow the sunset line.
//
// Generated by precompute/build_path.py. Do not edit by hand: run the script again.
"""


def trace() -> dict:
    north, south, centre = [], [], []
    lon = LON_FROM
    while lon <= LON_GIVE_UP:
        cut = eclipse.path_at(lon)
        if cut is None:
            break
        north.append([round(cut.north, 3), lon])
        south.append([round(cut.south, 3), lon])
        if cut.centre is not None:
            centre.append([round(cut.centre, 3), lon])
        print(f"\r  {lon:.2f} E", end="", flush=True)
        lon = round(lon + LON_STEP, 6)
    print()
    return {"deltaT": eclipse.DELTA_T_SECONDS, "north": north, "south": south, "centre": centre}


def main() -> None:
    print("Tracing the path of totality")
    path = trace()
    OUT.write_text(HEADER + "export const ECLIPSE_PATH = "
                   + json.dumps(path, separators=(",", ":")) + ";\n",
                   encoding="utf-8", newline="\n")
    print(f"  wrote {OUT.name}: {len(path['north'])} points per limit, "
          f"{path['north'][0][1]:.2f} E to {path['north'][-1][1]:.2f} E, "
          f"ΔT {path['deltaT']} s")


if __name__ == "__main__":
    main()
